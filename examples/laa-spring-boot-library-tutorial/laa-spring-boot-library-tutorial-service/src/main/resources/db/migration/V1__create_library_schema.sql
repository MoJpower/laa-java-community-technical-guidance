CREATE TABLE authors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    CONSTRAINT uk_authors_name UNIQUE (name)
);

CREATE TABLE books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    publication_year INTEGER,
    isbn VARCHAR(13),
    author_id BIGINT NOT NULL,
    CONSTRAINT ck_books_title_not_blank CHECK (length(trim(title)) > 0),
    CONSTRAINT ck_books_publication_year CHECK (
        publication_year IS NULL OR publication_year BETWEEN 1450 AND 2100
    ),
    CONSTRAINT ck_books_isbn CHECK (
        isbn IS NULL OR isbn ~ '^([0-9]{9}[0-9X]|[0-9]{13})$'
    ),
    CONSTRAINT fk_books_author FOREIGN KEY (author_id) REFERENCES authors (id)
);

CREATE INDEX idx_books_author_id ON books (author_id);
CREATE INDEX idx_books_publication_year ON books (publication_year);
